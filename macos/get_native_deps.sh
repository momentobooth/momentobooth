#!/usr/bin/env bash
# Downloads the prebuilt native dependencies (libgphoto2 and its dependencies) from https://github.com/momentobooth/native-deps.
#
# Extracts the bundle to .native_deps/macos-arm64 and writes .cargo/config.toml in the repository root, so that Cargo finds the
# libraries through pkg-config. At build time, macos/embed_native_deps.sh copies the runtime libraries into the app bundle.
#
# Usage: macos/get_native_deps.sh [zip]
# With a zip, that locally built bundle is used instead of the pinned release, e.g. to test a new build. Its checksum is not verified.

set -euo pipefail

release=libgphoto2-2.5.34-2
asset=libgphoto2-macos-arm64.zip
sha256=4c86cfe86b2c6dad5f452f4434b7405e2aa7f9f4f7525b6b7cd5c625a672d61e

if [[ $# -gt 1 ]]; then
  echo "Usage: $0 [zip]" >&2
  exit 1
fi

repository_root=$(cd "$(dirname "$0")/.." && pwd)
destination=$repository_root/.native_deps/macos-arm64
marker=$destination/.source

zip=${1:-}
if [[ -n "$zip" ]]; then
  # Includes the checksum, so a rebuilt zip at the same path is extracted again.
  source="$(cd "$(dirname "$zip")" && pwd)/$(basename "$zip")@$(shasum -a 256 "$zip" | cut -d ' ' -f 1)"
else
  source="$release/$asset@$sha256"
fi

if [[ -f "$marker" && "$(cat "$marker")" == "$source" ]]; then
  echo "Native dependencies are up to date ($source)"
else
  if [[ -z "$zip" ]]; then
    download_directory=$(mktemp -d)
    trap 'rm -rf "$download_directory"' EXIT
    zip=$download_directory/$asset
    echo "Downloading $release/$asset"
    curl -fsSL -o "$zip" "https://github.com/momentobooth/native-deps/releases/download/$release/$asset"
    actual_sha256=$(shasum -a 256 "$zip" | cut -d ' ' -f 1)
    if [[ "$actual_sha256" != "$sha256" ]]; then
      echo "Checksum mismatch for $asset, expected $sha256 but got $actual_sha256" >&2
      exit 1
    fi
  fi

  rm -rf "$destination"
  mkdir -p "$destination"
  # unzip keeps the symbolic links in the bundle, which the linker needs to find the libraries.
  unzip -q "$zip" -d "$destination"
  echo "$source" > "$marker"
  echo "Extracted native dependencies to $destination"
fi

# Cargo searches for configuration in the parent directories of the working directory, which includes this repository root for both cargo
# commands in rust/ and the Flutter build (cargokit runs cargo from build/macos/Build/Intermediates.noindex/...).
cargo_config=$repository_root/.cargo/config.toml
generated_header='# Generated by macos/get_native_deps.sh, do not edit.'
if [[ -f "$cargo_config" && "$(head -n 1 "$cargo_config")" != "$generated_header" ]]; then
  echo "$cargo_config exists but was not generated by this script, refusing to overwrite it" >&2
  exit 1
fi
mkdir -p "$(dirname "$cargo_config")"
cat > "$cargo_config" <<EOF
$generated_header
[env]
PKG_CONFIG_PATH = { value = '$destination/lib/pkgconfig', force = true }
EOF
